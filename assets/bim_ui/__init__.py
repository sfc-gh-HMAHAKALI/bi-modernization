"""
bim_ui — enterprise dashboard component kit for Streamlit-in-Snowflake.

Generated by the bi-modernization skill. Targets the SiS container runtime
(Streamlit 1.50+, PyPI packages, cross-session caching).

The kit exists to make one class of problem impossible rather than caught late:
inconsistent number formatting, clipped chart labels, colors that mean two
different things, tables you cannot sort, and panels that render blank when a
filter excludes everything.

Layout of the kit:

    theme       semantic color roles, palette resolution, WCAG auditing
    fmt         one formatting code path (KPI, axis, tooltip, grid cell agree)
    states      deliberate empty / error / loading / no-permission states
    filters     cross-filter store with exclude-self, URL state, drill-down
    charts      chart builders with reference lines and computed label headroom
    grid        native st.dataframe wrapper with column_config and export
    kpi         KPI cards with sparkline and progress-vs-target
    provenance  freshness / row count / source lineage banner

Usage sketch:

    from bim_ui import theme, fmt, filters, charts, grid, kpi, provenance

    palette = theme.resolve_palette(visuals)
    formats = fmt.FormatRegistry().load_visuals(visuals)
    ctx = UIContext(palette=palette, formats=formats)
"""

