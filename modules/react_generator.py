def _gen_snowflake_lib() -> str:
    return textwrap.dedent("""\
        /**
         * Snowflake query helper for Snowflake App Runtime.
         * Uses the injected window.__SNOWFLAKE_HOST__ and PAT/session token.
         */

        declare const window: Window & {
          __SNOWFLAKE_HOST__?: string;
          __SNOWFLAKE_TOKEN__?: string;
        };

        const getHost = (): string =>
          window.__SNOWFLAKE_HOST__ ??
          process.env.NEXT_PUBLIC_SNOWFLAKE_HOST ??
          "";

        const getToken = (): string =>
          window.__SNOWFLAKE_TOKEN__ ??
          process.env.NEXT_PUBLIC_SNOWFLAKE_TOKEN ??
          "";

        export async function query<T = Record<string, unknown>>(
          sql: string
        ): Promise<T[]> {
          const host = getHost();
          if (!host) {
            // Development mode: return empty dataset
            console.warn("[snowflake] No host configured — returning empty result.");
            return [];
          }

          const res = await fetch(`https://${host}/api/v2/statements`, {
            method: "POST",
            headers: {
              "Content-Type": "application/json",
              Authorization: `Bearer ${getToken()}`,
              "X-Snowflake-Authorization-Token-Type": "KEYPAIR_JWT",
            },
            body: JSON.stringify({
              statement: sql,
              timeout: 30,
              resultSetMetaData: { format: "jsonv2" },
            }),
          });

          if (!res.ok) {
            const err = await res.text();
            throw new Error(`Snowflake query failed: ${err}`);
          }

          const data = await res.json();
          const cols: string[] = (data.resultSetMetaData?.rowType ?? []).map(
            (c: { name: string }) => c.name
          );
          return (data.data ?? []).map((row: unknown[]) =>
            Object.fromEntries(cols.map((c, i) => [c, row[i]])) as T
          );
        }


        export async function callAgent(
          agentFqn: string,
          message: string
        ): Promise<string> {
          const host = getHost();
          if (!host) return "Agent not available in development mode.";

          const res = await fetch(`https://${host}/api/v2/cortex/agent:run`, {
            method: "POST",
            headers: {
              "Content-Type": "application/json",
              Authorization: `Bearer ${getToken()}`,
            },
            body: JSON.stringify({
              agent: agentFqn,
              messages: [{ role: "user", content: message }],
              stream: false,
            }),
          });

          if (!res.ok) return `Agent error: ${await res.text()}`;
          const data = await res.json();
          return data?.choices?.[0]?.message?.content ?? "No response.";
        }
    """)


