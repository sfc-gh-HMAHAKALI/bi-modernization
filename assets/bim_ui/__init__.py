@dataclass
class UIContext:
    """Shared rendering context threaded through every kit component.

    Passing one object rather than loose palette/format arguments is what keeps
    a chart, a KPI card, and a grid cell from disagreeing about how the same
    field should look.
    """

    palette: "theme.Palette" = field(default_factory=theme.resolve_palette)
    formats: "fmt.FormatRegistry" = field(default_factory=fmt.FormatRegistry)
    demo_mode: bool = False

    # Attainment thresholds. Carried on the context so a dashboard can define
    # "on track" once instead of each chart inventing its own cutoffs.
    good_at: float = 0.95
    warn_at: float = 0.80

    @classmethod
    def from_visuals(
        cls,
        visuals: dict | None = None,
        *,
        brand_colors=None,
        background: str | None = None,
        demo_mode: bool = False,
        **kwargs,
    ) -> "UIContext":
        """Build a context from extract-visuals output."""
        return cls(
            palette=theme.resolve_palette(
                visuals, brand_colors=brand_colors, background=background
            ),
            formats=fmt.FormatRegistry().load_visuals(visuals),
            demo_mode=demo_mode,
            **kwargs,
        )

    def status_color(self, ratio: float) -> str:
        return self.palette.status(ratio, good_at=self.good_at, warn_at=self.warn_at)

    def fmt_field(self, field_name: str, value, dtype=None) -> str:
        return self.formats.render(field_name, value, dtype)

    def contrast_report(self) -> list["theme.ContrastFinding"]:
        return theme.audit_contrast(self.palette)


def apply_theme(ctx: "UIContext") -> None:
    """Inject the kit's base CSS. Call once, immediately after set_page_config.

    Only covers what .streamlit/config.toml cannot express (the header band, KPI
    cards, chips, provenance strip). Widget and dataframe theming comes from
    config.toml, which is more reliable across Streamlit versions than CSS that
    targets internal test IDs.
    """
    import streamlit as st

    st.markdown(theme.base_css(ctx.palette), unsafe_allow_html=True)
