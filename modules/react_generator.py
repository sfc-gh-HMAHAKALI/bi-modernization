def _gen_dashboard_page_tsx(
    dashboard: dict,
    inventory: dict,
    table_name: str,
    semantic_view: str | None,
) -> str:
    """Generate a Next.js page for one dashboard."""
    name = dashboard.get("name", "Dashboard")
    # Normalize: sheets may be plain strings (zone names with no field metadata)
    # or full dicts produced by extract_dashboard_field_usage.  Always work with dicts.
    sheets = [
        s if isinstance(s, dict) else {"name": s, "fields_by_datasource": {}}
        for s in dashboard.get("sheets", [])
    ]

    dims = inventory.get("dimensions", [])
    measures = (inventory.get("measures", []) +
                inventory.get("metrics", []) +
                inventory.get("facts", []))

    raw_filters = inventory.get("parameters", []) or inventory.get("filters", [])
    filter_widgets = infer_filter_widgets(raw_filters) if raw_filters else []

    query_target = semantic_view or table_name or "DB.SCHEMA.TABLE -- TODO: replace"

    imports = {
        "BarChart", "LineChart", "AreaChart", "PieChart",
        "ScatterChart", "MetricCard", "DataTable"
    }
    used_components: set[str] = set()

    chart_blocks: list[str] = []

    for i, sheet in enumerate(sheets):
        sname = sheet.get("name", f"Sheet {i+1}")
        chart_type = sheet.get("chart_type_echarts") or sheet.get("chart_type_plotly") or "bar"
        component = echarts_component_name(chart_type)

        if component is None or chart_type == "filter":
            continue  # filter slicers go into FilterPanel

        used_components.add(component)

        # Field resolution (simplified)
        sheet_fields = []
        for vals in sheet.get("fields_by_datasource", {}).values():
            sheet_fields.extend(vals if isinstance(vals[0] if vals else None, str) else
                                 [v.get("name", "") if isinstance(v, dict) else v for v in vals])

        dim_names = [d["name"] for d in dims if d.get("name") in sheet_fields][:2]
        meas_names = [m["name"] for m in measures if m.get("name") in sheet_fields][:1]
        if not dim_names and dims:
            dim_names = [dims[0]["name"]]
        if not meas_names and measures:
            meas_names = [measures[0]["name"]]

        x_field = (dim_names[0].upper() if dim_names else "CATEGORY")
        y_field = (meas_names[0].upper() if meas_names else "VALUE")

        state_var = f"data{i}"
        sql = (
            f'SELECT "{x_field}", SUM("{y_field}") AS "{y_field}" '
            f'FROM {query_target} GROUP BY "{x_field}" '
            f'ORDER BY "{y_field}" DESC LIMIT 200'
        )

        props_map = {
            "BarChart":    f'data={{{state_var}}} xField="{x_field}" yField="{y_field}" title="{sname}"',
            "LineChart":   f'data={{{state_var}}} xField="{x_field}" yField="{y_field}" title="{sname}"',
            "AreaChart":   f'data={{{state_var}}} xField="{x_field}" yField="{y_field}" title="{sname}"',
            "PieChart":    f'data={{{state_var}}} nameField="{x_field}" valueField="{y_field}" title="{sname}"',
            "ScatterChart":f'data={{{state_var}}} xField="{x_field}" yField="{y_field}" title="{sname}"',
            "MetricCard":  f'label="{sname}" value={{String({state_var}[0]?.["{y_field}"] ?? 0)}}',
            "DataTable":   f'data={{{state_var}}} title="{sname}"',
        }

        chart_blocks.append(textwrap.dedent(f"""\
              {{/* {sname} */}}
              <div className="chart-card">
                <{component} {props_map.get(component, "")} />
              </div>
        """))

    # State initialisation
    state_inits = "\n".join(
        f'  const [data{i}, setData{i}] = useState<Record<string,unknown>[]>([]);'
        for i in range(len(chart_blocks))
    )

    # Data fetch hooks
    sql_list = []
    for i, sheet in enumerate(sheets):
        dim_names = []
        meas_names = []
        for vals in sheet.get("fields_by_datasource", {}).values():
            for v in vals:
                n = v if isinstance(v, str) else v.get("name", "")
                if any(d["name"] == n for d in dims):
                    dim_names.append(n.upper())
                elif any(m["name"] == n for m in measures):
                    meas_names.append(n.upper())
        x = dim_names[0] if dim_names else (dims[0]["name"].upper() if dims else "CATEGORY")
        y = meas_names[0] if meas_names else (measures[0]["name"].upper() if measures else "VALUE")
        sql_list.append(
            f'  query(`SELECT "{x}", SUM("{y}") AS "{y}" FROM {query_target} '
            f'GROUP BY "{x}" ORDER BY "{y}" DESC LIMIT 200`).then(setData{i});'
        )

    fetch_block = "\n".join(sql_list)
    imports_str = ", ".join(sorted(used_components))
    fp_import = 'import FilterPanel from "@/components/FilterPanel";\n' if filter_widgets else ""

    return textwrap.dedent(f"""\
        "use client";
        import {{ useState, useEffect }} from "react";
        import {{ {imports_str} }} from "@/components/charts";
        {fp_import}import {{ query }} from "@/lib/snowflake";
        import {{ FilterState }} from "@/lib/types";

        export default function {_safe_var(name)}Dashboard() {{
          {state_inits}
          const [_filters, setFilters] = useState<FilterState>({{}});

          useEffect(() => {{
            {fetch_block}
          }}, [_filters]);

          return (
            <div className="flex h-full">
              {"<FilterPanel onChange={f => setFilters(prev => ({ ...prev, ...f }))} />" if filter_widgets else ""}
              <div className="flex-1 p-6 overflow-y-auto">
                <h1 className="text-2xl font-bold text-slate-900 mb-6">{name}</h1>
                <div className="grid grid-cols-1 md:grid-cols-2 xl:grid-cols-3 gap-4">
        {"".join(chart_blocks)}
                </div>
              </div>
            </div>
          );
        }}
    """)


