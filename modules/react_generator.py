def generate(
    inventory_path: str,
    output_dir: str,
    app_name: str = "BI Suite",
    semantic_view: str | None = None,
    embed_agent: str | None = None,
    dashboards_filter: list[str] | None = None,
) -> dict[str, Any]:
    """
    Generate a full Next.js + ECharts project at output_dir.
    Returns a structured result dict.
    """
    with open(inventory_path) as fh:
        inventory = json.load(fh)

    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    dashboards = inventory.get("dashboards", [])
    if dashboards_filter:
        dashboards = [d for d in dashboards if d.get("name") in dashboards_filter]
    if not dashboards:
        dashboards = [{"name": "Dashboard", "sheets": inventory.get("worksheets", [])}]

    tables = inventory.get("tables", [])
    primary_table = ""
    if tables:
        t = tables[0]
        db = inventory.get("snowflake_target", {}).get("database", "DB")
        sch = inventory.get("snowflake_target", {}).get("schema", "SCHEMA")
        tname = t.get("snowflake_name") or t.get("name", "TABLE")
        primary_table = f"{db}.{sch}.{tname}"

    raw_filters = inventory.get("parameters", []) or inventory.get("filters", [])
    filter_widgets = infer_filter_widgets(raw_filters) if raw_filters else []

    generated: list[dict] = []

    def write(rel: str, content: str) -> None:
        p = out / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")
        generated.append({"path": str(p)})

    # Root config files
    write("app.yml",               _gen_app_yml(app_name))
    write("package.json",          _gen_package_json(app_name))
    write("tailwind.config.ts",    _gen_tailwind_config())
    write("tsconfig.json",         _gen_tsconfig())

    # Source files
    write("src/app/globals.css",   _gen_globals_css())
    write("src/lib/snowflake.ts",  _gen_snowflake_lib())
    write("src/lib/types.ts",      _gen_types())

    # Chart components
    write("src/components/charts/BarChart.tsx",    _gen_bar_chart_tsx())
    write("src/components/charts/LineChart.tsx",   _gen_line_chart_tsx())
    write("src/components/charts/AreaChart.tsx",   _gen_area_chart_tsx())
    write("src/components/charts/PieChart.tsx",    _gen_pie_chart_tsx())
    write("src/components/charts/ScatterChart.tsx",_gen_scatter_chart_tsx())
    write("src/components/charts/MetricCard.tsx",  _gen_metric_card_tsx())
    write("src/components/charts/DataTable.tsx",   _gen_data_table_tsx())
    write("src/components/charts/index.ts",        _gen_charts_index())

    # Optional components
    write("src/components/FilterPanel.tsx", _gen_filter_panel_tsx(filter_widgets))
    if embed_agent:
        write("src/components/AgentChat.tsx", _gen_agent_chat_tsx(embed_agent))

    # App layout + home
    dash_names = [d.get("name", "") for d in dashboards]
    write("src/app/layout.tsx", _gen_layout_tsx(app_name, dash_names, embed_agent))
    write("src/app/page.tsx",   _gen_home_page_tsx(dash_names))

    # Dashboard pages
    for dash in dashboards:
        slug = _slugify(dash.get("name", "dashboard"))
        page_content = _gen_dashboard_page_tsx(dash, inventory, primary_table, semantic_view)
        write(f"src/app/dashboard/{slug}/page.tsx", page_content)

    return {
        "status": "ok",
        "command": "generate-react",
        "output_dir": output_dir,
        "app_name": app_name,
        "generated_files": generated,
        "dashboard_count": len(dashboards),
        "file_count": len(generated),
        "embed_agent": embed_agent,
        "semantic_view": semantic_view,
        "next_steps": [
            f"cd {output_dir} && npm install",
            "snow app deploy  # via snowflake-apps skill",
        ],
    }
